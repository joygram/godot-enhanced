// GodotSharp 의 엔진 함수 포인터(UnmanagedCallbacks) 서명 → wasm 인터프리터 쿠키, 템플릿 m2n 표와 대조
// 사용: dotnet run misc/scripts/web_signatures.cs <GodotSharp.dll> <wasm_m2n_invoke.g.h> [--emit <출력.cs>]
//   --emit: 서명마다 DllImport 선언을 만들어 GetRuntimePack 에 넣음 → 생성기가 m2n 트램펄린 생성
using System.Reflection;
using System.Runtime.InteropServices;
using System.Text;
using System.Text.RegularExpressions;

var asm = Assembly.LoadFrom(args[0]);
var t = asm.GetTypes().First(x => x.Name == "UnmanagedCallbacks");

// mono 의 '스칼라 값형식'(필드 하나짜리, 재귀) → 그 원시형, 아니면 null
static Type? Scalar(Type x)
{
	while (x.IsValueType && !x.IsPrimitive && !x.IsEnum && !x.IsPointer)
	{
		var fs = x.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic);
		if (fs.Length != 1) return null;
		x = fs[0].FieldType;
	}
	return x.IsEnum ? Enum.GetUnderlyingType(x) : x;
}
static string C(Type x)
{
	if (x.IsPointer || x.IsByRef || x.IsFunctionPointer || x == typeof(IntPtr) || x == typeof(UIntPtr)) return "I";
	if (x == typeof(void)) return "V";
	if (x == typeof(long) || x == typeof(ulong)) return "L";
	if (x == typeof(float)) return "F";
	if (x == typeof(double)) return "D";
	if (x.IsPrimitive || x.IsEnum) return "I";
	var s = Scalar(x);
	return s != null ? C(s) : "S(" + x.Name + ")";
}

var sigs = new SortedDictionary<string, (Type ret, Type[] ps, List<string> names)>();
foreach (var f in t.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic))
{
	var ft = f.FieldType;
	if (!ft.IsFunctionPointer) continue;
	var ret = ft.GetFunctionPointerReturnType();
	var ps = ft.GetFunctionPointerParameterTypes();
	var s = C(ret) + string.Concat(ps.Select(C));
	if (!sigs.TryGetValue(s, out var e)) sigs[s] = e = (ret, ps, new());
	e.names.Add(f.Name);
}
var have = Regex.Matches(File.ReadAllText(args[1]), @"^wasm_invoke_(\w+)\s*\(", RegexOptions.Multiline).Select(m => m.Groups[1].Value.ToUpperInvariant()).ToHashSet();
Console.WriteLine($"서명 {sigs.Count}종, 표 {have.Count}종");
foreach (var (s, e) in sigs)
	if (!have.Contains(s)) Console.WriteLine($"없음 {s}  ({e.names.Count}개: {string.Join(", ", e.names.Take(3))})");

int emit = Array.IndexOf(args, "--emit");
if (emit < 0) return;

// 값형식은 같은 크기·같은 스칼라 여부의 대역 구조체로
var structs = new SortedDictionary<string, string>();
string T(Type x)
{
	if (x == typeof(void)) return "void";
	if (x.IsPointer || x.IsByRef || x.IsFunctionPointer || x == typeof(IntPtr) || x == typeof(UIntPtr)) return "nint";
	if (x.IsEnum) x = Enum.GetUnderlyingType(x);
	if (x.IsPrimitive) return x == typeof(bool) ? "byte" : x.FullName!;
	var s = Scalar(x);
	if (s != null) return T(s);
	int size = Marshal.SizeOf(x);
	var name = $"S{size}";
	structs[name] = $"[StructLayout(LayoutKind.Sequential, Size = {size})] internal struct {name} {{ public nint a; public nint b; }}";
	return name;
}
var sb = new StringBuilder();
sb.AppendLine("// <auto-generated/> misc/scripts/web_signatures (GodotSharp UnmanagedCallbacks 서명)");
sb.AppendLine("// GodotSharp 는 엔진 함수를 함수 포인터로 부름 → wasm 인터프리터는 서명별 트램펄린이 필요한데,");
sb.AppendLine("// 생성기는 P/Invoke 선언만 봄. 서명마다 한 번씩 선언해 wasm_m2n_invoke.g.h 에 넣게 함 (호출되지 않음).");
sb.AppendLine("using System.Runtime.InteropServices;");
sb.AppendLine("namespace Godot.NativeInterop;");
var decls = new StringBuilder();
int i = 0;
foreach (var (s, e) in sigs)
	decls.AppendLine($"\t[DllImport(\"godotsharp_signatures\")] internal static extern {T(e.ret)} s{i++}({string.Join(", ", e.ps.Select((p, k) => $"{T(p)} a{k}"))}); // {s}: {e.names[0]}");
foreach (var s in structs.Values) sb.AppendLine(s);
sb.AppendLine("internal static unsafe class GodotSharpSignatures");
sb.AppendLine("{");
sb.Append(decls);
sb.AppendLine("}");
File.WriteAllText(args[emit + 1], sb.ToString());
Console.WriteLine($"→ {args[emit + 1]} ({sigs.Count}개 선언, 대역 구조체 {structs.Count}개)");
